#!/usr/bin/env node
// Keeps the code <-> Figma mapping honest.
//
//   npm run figma:sync                 regenerate figma/manifest.json from figma/component-map.json
//   npm run figma:check                list tokens / components / pages changed since the last Figma push
//   npm run figma:mark -- Button Chip  record these as pushed to Figma (use `all` for everything)
//
// Hashes cover file contents, so any edit to a component (or a page's import tree) marks it stale.
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const mapPath = join(root, "figma/component-map.json");
const manifestPath = join(root, "figma/manifest.json");
const syncedPath = join(root, "figma/synced.json");

const read = (rel) => (existsSync(join(root, rel)) ? readFileSync(join(root, rel), "utf8") : "");
const hash = (text) => createHash("sha1").update(text).digest("hex").slice(0, 10);
const asList = (v) => (Array.isArray(v) ? v : [v]);

const map = JSON.parse(read("figma/component-map.json"));

// Resolve a TS/TSX import specifier to a repo file, or null for packages / unresolved paths.
function resolveImport(from, spec) {
  let base;
  if (spec.startsWith("@/")) base = spec.slice(2);
  else if (spec.startsWith(".")) base = join(dirname(from), spec);
  else return null;
  for (const ext of ["", ".tsx", ".ts", ".css", "/index.tsx", "/index.ts"]) {
    const rel = base + ext;
    if (/\.(tsx?|css)$/.test(rel) && existsSync(join(root, rel))) return rel;
  }
  return null;
}

// Every file a page pulls in, following local imports transitively.
function importTree(entry) {
  const seen = new Set();
  const walk = (file) => {
    if (seen.has(file)) return;
    seen.add(file);
    if (!/\.tsx?$/.test(file)) return;
    const src = read(file);
    for (const m of src.matchAll(/(?:from|import)\s+["']([^"']+)["']/g)) {
      const dep = resolveImport(file, m[1]);
      if (dep) walk(dep);
    }
  };
  walk(entry);
  return [...seen].sort();
}

const tokenHash = hash(read(map.tokens.file));
const stylesHash = hash(read(map.tokens.styles));

const components = map.components.map((c) => {
  const files = asList(c.file);
  return { ...c, hash: hash(files.map(read).join("\n")) };
});

const pages = map.pages.map((p) => {
  const files = importTree(p.entry);
  const set = new Set(files);
  const uses = components
    .filter((c) => asList(c.file).some((f) => set.has(f)))
    .map((c) => c.react);
  return { ...p, uses, files, hash: hash(files.map(read).join("\n")) };
});

const manifest = {
  $comment: "Generated by scripts/figma-sync.mjs. Do not edit; edit figma/component-map.json instead.",
  figmaFile: map.figmaFile,
  tokens: { hash: tokenHash, stylesHash, file: map.tokens.file, figma: map.tokens.figma, note: map.tokens.note },
  components,
  pages,
};

const args = process.argv.slice(2);
const cmd = args[0] ?? "sync";
const synced = existsSync(syncedPath) ? JSON.parse(readFileSync(syncedPath, "utf8")) : {};

if (cmd === "sync") {
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
  console.log(`manifest.json: ${components.length} components, ${pages.length} pages`);
  process.exit(0);
}

if (cmd === "mark") {
  const names = args.slice(1);
  if (!names.length) {
    console.error("usage: figma:mark -- <Name...> | all   (names: tokens, a component's `react` name, or a page name)");
    process.exit(1);
  }
  const all = names.includes("all");
  const next = { tokens: synced.tokens, styles: synced.styles, components: { ...synced.components }, pages: { ...synced.pages } };
  if (all || names.includes("tokens")) {
    next.tokens = tokenHash;
    next.styles = stylesHash;
  }
  for (const c of components) if (all || names.includes(c.react)) next.components[c.react] = c.hash;
  for (const p of pages) if (all || names.includes(p.name)) next.pages[p.name] = p.hash;
  writeFileSync(syncedPath, JSON.stringify(next, null, 2) + "\n");
  console.log("synced.json updated");
  process.exit(0);
}

if (cmd === "check") {
  const stale = (kind, items, key) =>
    items.filter((i) => i.status !== "missing" && synced[kind]?.[i[key]] !== i.hash);
  const out = (title, rows) => {
    if (!rows.length) return;
    console.log(`\n${title}`);
    for (const r of rows) console.log("  " + r);
  };
  console.log(`Figma file ${map.figmaFile}`);
  if (synced.tokens !== tokenHash) console.log("\nTokens: lib/tokens.ts changed (or never synced) -> update variables and styles first");
  if (synced.styles !== stylesHash) console.log("Styles: app/ui.css changed -> re-check every shared component against it");
  out("Components to update in Figma", stale("components", components, "react").map((c) => `${c.react}  [${c.status}]  ${c.figma}`));
  out("Components not in Figma yet", components.filter((c) => c.status === "missing").map((c) => `${c.react}  ->  ${c.figma}${c.notes ? "  (" + c.notes + ")" : ""}`));
  out("Pages to refresh", stale("pages", pages, "name").map((p) => `${p.name}  ${p.route}`));
  console.log("\nAfter pushing to Figma: npm run figma:mark -- <Name...>");
  process.exit(0);
}

console.error(`unknown command: ${cmd}`);
process.exit(1);
